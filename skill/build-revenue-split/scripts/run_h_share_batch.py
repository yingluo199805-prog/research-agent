def ensure_static_source_workbook(path, sheet_name, years, data, unit_label="（单位：百万元，CNY）"):
    """Create/update a minimal H-share source sheet when iFinD exports are unavailable."""
    if os.path.exists(path):
        wb = openpyxl.load_workbook(path)
    else:
        wb = openpyxl.Workbook()
        wb.remove(wb.active)
    if sheet_name in wb.sheetnames:
        del wb[sheet_name]
    ws = wb.create_sheet(sheet_name, 0)
    ycol = {y: 2 + i for i, y in enumerate(years)}

    def write_section(start_row, title, rows):
        ws.cell(start_row, 1, title).font = Font(bold=True)
        ws.cell(start_row + 1, 1, unit_label)
        for y in years:
            ws.cell(start_row + 2, ycol[y], f"{y} 年报").font = Font(bold=True)
        r = start_row + 3
        for label, key in rows:
            ws.cell(r, 1, label)
            for y in years:
                ws.cell(r, ycol[y], data.get(y, {}).get(key))
            r += 1
        return r + 2

    r = write_section(1, "一、利润表", [
        ("营业收入", "收入"),
        ("销售成本", "销售成本"),
        ("毛利", "毛利"),
        ("销售开支", "销售费用"),
        ("行政开支", "管理费用"),
        ("研发开支", "研发成本"),
        ("其他收入及收益净额", "其他收入及收益"),
        ("经营利润/亏损", "经营利润"),
        ("财务收入", "融资收入"),
        ("财务成本", "融资成本"),
        ("联营公司损益", "联营"),
        ("税前利润/亏损", "税前利润"),
        ("所得税费用", "所得税"),
        ("归母净利润/亏损", "归母净利润"),
        ("少数股东损益", "少数股东损益"),
        ("会计准则", "会计准则"),
    ])
    write_section(r, "二、资产负债表", [
        ("资产总计", "资产总计"),
        ("负债合计", "负债合计"),
        ("权益合计", "权益合计"),
    ])
    ws.column_dimensions["A"].width = 34
    for c in ycol.values():
        ws.column_dimensions[openpyxl.utils.get_column_letter(c)].width = 12
    wb.save(path)


def read_geely_note_data(path, years):
    """Read values from the existing 吉利附注底稿 before rebuilding it."""
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["吉利附注底稿"]
    col = {y: 3 + i for i, y in enumerate(years)}

    label_key = {
        "薪金、工资及其他福利": "薪金福利",
        "退休福利计划供款": "退休供款",
        "以权益结算股份为基础之付款": "股份支付",
        "折旧－自置资产": "折旧",
        "摊销－使用权资产折旧": "使用权资产折旧",
        "摊销－预付土地租赁款项": "土地摊销",
        "摊销－无形资产": "无形资产摊销",
        "研发成本": "研发成本",
        "销售费用": "销售费用",
        "管理费用": "管理费用",
        "融资成本": "融资成本",
        "融资收入": "融资收入",
        "保证型保修": "售后",
        "质保金": "售后",
        "业务费用（已披露第三方口径）": "业务费用第三方",
    }
    row_key = {}
    for r in range(1, ws.max_row + 1):
        label = ws.cell(r, 2).value
        if not label:
            continue
        label = str(label)
        for token, key in label_key.items():
            if token in label and key not in row_key.values():
                row_key[r] = key
                break

    out = {}
    for y in years:
        d = {}
        for r, key in row_key.items():
            v = ws.cell(r, col[y]).value
            d[key] = 0 if v is None else float(v)
        for key in [
            "薪金福利", "退休供款", "股份支付", "折旧", "使用权资产折旧", "土地摊销", "无形资产摊销",
            "研发成本", "销售费用", "管理费用", "融资成本", "融资收入", "售后", "业务费用第三方",
        ]:
            d.setdefault(key, 0)
        d["员工合计"] = d["薪金福利"] + d["退休供款"] + d["股份支付"]
        d["业务费用第三方"] = max(
            d["研发成本"] + d["销售费用"] + d["管理费用"]
            - d["员工合计"] - d["折旧"] - d["使用权资产折旧"] - d["土地摊销"] - d["无形资产摊销"],
            0,
        )
        out[y] = d
    return out


