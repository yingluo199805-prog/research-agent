def convert(prefix, folder, fy_map):
    for f in sorted(glob.glob(os.path.join(common.BASE, folder, "*.pdf"))):
        pre = os.path.basename(f).split("：")[0]
        fy = fy_map.get(pre)
        if fy:
            pdf_to_text(f, common.txt_path(prefix, fy))

